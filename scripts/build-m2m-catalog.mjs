// Builds src/assets/mesh2motionData.ts from the Mesh2Motion asset library (CC0 animations, rigged models, props).
// Reads each GLB's JSON chunk at a pinned commit: clip names per animation file, and the native size of props.
// Run: npm run catalog:m2m [commit]   (defaults to the latest commit on main)
import { Buffer } from 'node:buffer';
import { writeFileSync } from 'node:fs';
import process from 'node:process';

const REPO = 'Mesh2Motion/mesh2motion-app';
const OUT = new URL('../src/assets/mesh2motionData.ts', import.meta.url);
const ANIMATION_FILES = [
  'human-base-animations.glb',
  'human-addon-animations.glb',
  'human-mocap-animations.glb',
  'fox-animations.glb',
  'bird-animations.glb',
  'kaiju-animations.glb',
  'shark-animations.glb',
  'horse-animations.glb',
  'dragon-animations.glb',
  'spider-animations.glb',
  'snake-animations.glb',
];
/** Root-motion duplicates (the in-place versions exist) and bind poses are left out. */
const SKIP_CLIP = /(^|[ _])RM$|^Rest[ _]Pose$/i;

const commit = process.argv[2] ?? (await (await fetch(`https://api.github.com/repos/${REPO}/commits/main`)).json()).sha;
if (!/^[0-9a-f]{40}$/.test(commit ?? '')) throw new Error(`Could not resolve a commit: ${commit}`);
const cdn = `https://cdn.jsdelivr.net/gh/${REPO}@${commit}/static/`;

/** The glTF JSON chunk of a GLB (the binary chunk is not needed). */
async function gltfJson(path) {
  const res = await fetch(cdn + path);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  return JSON.parse(buf.subarray(20, 20 + buf.readUInt32LE(12)).toString());
}

// --- Clips per animation file ---
const clips = {};
const seen = new Map();
for (const file of ANIMATION_FILES) {
  const names = (await gltfJson(`animations/${file}`)).animations.map((a) => a.name).filter((n) => !SKIP_CLIP.test(n));
  for (const n of names) {
    const family = file.split('-')[0];
    const key = `${family}:${n}`;
    if (seen.has(key)) console.warn(`Clip "${n}" is in both ${seen.get(key)} and ${file}; the first wins`);
    else seen.set(key, file);
  }
  clips[file] = names;
  console.log(`${file}: ${names.length} clips`);
}

// --- Props: native size (largest bounding-box side, metres) from accessor bounds and node transforms ---
const tree = await (await fetch(`https://api.github.com/repos/${REPO}/git/trees/${commit}?recursive=1`)).json();
const paths = tree.tree.map((t) => t.path);
const propFiles = paths.filter((p) => /^static\/props\/[^/]+\.glb$/.test(p)).map((p) => p.slice('static/props/'.length));
const previews = new Set(paths.filter((p) => p.startsWith('static/props/preview/')).map((p) => p.slice('static/props/preview/'.length).replace(/\.png$/, '')));

const props = [];
for (const file of propFiles) {
  const j = await gltfJson(`props/${file}`);
  const size = boundsSize(j);
  const name = file.replace(/\.glb$/, '');
  props.push([name, Math.round(size * 1000) / 1000, previews.has(name)]);
}
props.sort((a, b) => a[0].localeCompare(b[0]));
console.log(`props: ${props.length}`);

writeFileSync(
  OUT,
  `// Generated by scripts/build-m2m-catalog.mjs from ${REPO}@${commit}. Do not edit; run npm run catalog:m2m.

/** Pinned commit of the Mesh2Motion app repository whose static assets are loaded from jsDelivr. */
export const M2M_COMMIT = '${commit}';

/** Clip names in each animation file (root-motion duplicates and rest poses removed). */
export const M2M_CLIPS: Record<string, readonly string[]> = ${JSON.stringify(clips, null, 2)};

/** Props: [file name without .glb, largest side in metres, has a preview image]. */
export const M2M_PROPS: ReadonlyArray<readonly [string, number, boolean]> = ${JSON.stringify(props)};
`,
);
console.log(`Wrote ${OUT.pathname}`);

function boundsSize(j) {
  const parent = {};
  j.nodes.forEach((n, i) => (n.children ?? []).forEach((c) => (parent[c] = i)));
  const local = (n) => {
    if (n.matrix) return n.matrix;
    const [x, y, z, w] = n.rotation ?? [0, 0, 0, 1];
    const [sx, sy, sz] = n.scale ?? [1, 1, 1];
    const [tx, ty, tz] = n.translation ?? [0, 0, 0];
    return [(1 - 2 * (y * y + z * z)) * sx, 2 * (x * y + z * w) * sx, 2 * (x * z - y * w) * sx, 0, 2 * (x * y - z * w) * sy, (1 - 2 * (x * x + z * z)) * sy, 2 * (y * z + x * w) * sy, 0, 2 * (x * z + y * w) * sz, 2 * (y * z - x * w) * sz, (1 - 2 * (x * x + y * y)) * sz, 0, tx, ty, tz, 1];
  };
  const mul = (a, b) => {
    const o = new Array(16).fill(0);
    for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) for (let k = 0; k < 4; k++) o[c * 4 + r] += a[k * 4 + r] * b[c * 4 + k];
    return o;
  };
  const world = (i) => (parent[i] === undefined ? local(j.nodes[i]) : mul(world(parent[i]), local(j.nodes[i])));
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  j.nodes.forEach((n, i) => {
    if (n.mesh === undefined) return;
    const m = world(i);
    for (const p of j.meshes[n.mesh].primitives) {
      const a = j.accessors[p.attributes.POSITION];
      for (const x of [a.min[0], a.max[0]])
        for (const y of [a.min[1], a.max[1]])
          for (const z of [a.min[2], a.max[2]])
            for (let k = 0; k < 3; k++) {
              const v = m[k] * x + m[4 + k] * y + m[8 + k] * z + m[12 + k];
              min[k] = Math.min(min[k], v);
              max[k] = Math.max(max[k], v);
            }
    }
  });
  return Math.max(max[0] - min[0], max[1] - min[1], max[2] - min[2]);
}
